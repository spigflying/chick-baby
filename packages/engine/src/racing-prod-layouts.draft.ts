/** 角數統計：90° 彎（70–110°）、髮夾（≥150°）、S 彎（相鄰反向弧對）、掃彎（其他） */
export function cornerStats(pieces: LayoutPiece[]) {
  let c90 = 0, hp = 0, sb = 0, sw = 0;
  for (let i = 0; i < pieces.length; i++) { const p = pieces[i]; if (!('a' in p)) continue; const a = Math.abs(p.a);
    const q = pieces[i + 1];
    if (a >= 150) hp++; else if (a >= 70 && a <= 110) c90++;
    else if (q && 'a' in q && Math.sign(q.a) !== Math.sign(p.a) && Math.abs(q.a) < 70) { sb++; i++; } else sw++; }
  return { c90, hp, sbend: sb, sweep: sw };
}
